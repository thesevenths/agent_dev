"""ARR-03 M3 -- real Reacher-v5 action-conditioned dynamics model adapter.

No FakeRunner / MockEngine. Trajectories are generated by the actual
Gymnasium MuJoCo Reacher-v5 simulator; the dynamics model is a real trained
PyTorch MLP. Every arm records data hashes, applied config, model hash and
verified metrics. The simulator ground truth (target coordinates, generator
config) is retained evaluator-side and never enters the agent view.
"""
from __future__ import annotations

import hashlib
import json
import math
import threading
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import numpy as np

OBS_DIM = 10
ACTION_DIM = 2
INPUT_DIM = OBS_DIM + ACTION_DIM

_GYM_LOCK = threading.Lock()  # MuJoCo renderer / global state safety


def sha256_json(obj: Any) -> str:
    blob = json.dumps(obj, sort_keys=True, ensure_ascii=False,
                      separators=(",", ":"), default=str).encode("utf-8")
    return hashlib.sha256(blob).hexdigest()


def sha256_file(path: str | Path) -> str:
    h = hashlib.sha256()
    with Path(path).open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


@dataclass
class TrajectoryBatch:
    """Flattened (s_t, a_t, s_t+1) transitions plus per-episode sequences."""

    states: np.ndarray  # (N, OBS_DIM)
    actions: np.ndarray  # (N, ACTION_DIM)
    next_states: np.ndarray  # (N, OBS_DIM)
    episodes: list[list[tuple[np.ndarray, np.ndarray, np.ndarray]]] = field(
        default_factory=list)
    config: dict[str, Any] = field(default_factory=dict)

    @property
    def n(self) -> int:
        return int(self.states.shape[0])

    def digest(self) -> str:
        return sha256_json({
            "n": self.n,
            "config": self.config,
            "states": np.round(self.states, 8).tolist(),
            "actions": np.round(self.actions, 8).tolist(),
            "next_states": np.round(self.next_states, 8).tolist(),
        })


def generate_trajectories(*, seed: int, n_episodes: int, max_steps: int,
                          target_mode: str = "mixed",
                          action_mode: str = "random",
                          action_scale: float = 1.0) -> TrajectoryBatch:
    """Generate (s_t, a_t, s_{t+1}) from the REAL Reacher-v5 simulator.

    target_mode:
      - "center": target confined to a small central region
      - "far": target confined to an outer annulus
      - "mixed": target sampled across both (domain randomization)
    action_mode:
      - "random": uniform random torque in [-1, 1]
      - "biased": torque biased positive (poor action coverage)
      - "zero": torque forced to 0 (no action conditioning signal)
    """
    import gymnasium as gym  # lazy: unit tests need no simulator

    rng = np.random.default_rng(seed)
    states: list[np.ndarray] = []
    actions: list[np.ndarray] = []
    next_states: list[np.ndarray] = []
    episodes: list[list[tuple[np.ndarray, np.ndarray, np.ndarray]]] = []

    with _GYM_LOCK:
        env = gym.make("Reacher-v5")
        try:
            for ep in range(int(n_episodes)):
                env.reset(seed=int(seed) * 1000 + ep)
                # Place target according to mode by editing qpos[2:4].
                if target_mode == "center":
                    tgt = rng.uniform(-0.05, 0.05, size=2)
                elif target_mode == "far":
                    ang = rng.uniform(0, 2 * math.pi)
                    rad = rng.uniform(0.16, 0.20)
                    tgt = np.array([rad * math.cos(ang), rad * math.sin(ang)])
                elif target_mode == "mixed":
                    if ep % 2 == 0:
                        tgt = rng.uniform(-0.05, 0.05, size=2)
                    else:
                        ang = rng.uniform(0, 2 * math.pi)
                        rad = rng.uniform(0.16, 0.20)
                        tgt = np.array([rad * math.cos(ang), rad * math.sin(ang)])
                else:
                    raise ValueError(f"unknown target_mode {target_mode}")
                qpos = env.unwrapped.data.qpos.copy()
                qpos[2:4] = tgt
                # Reset velocities too, so the target placement is deterministic
                # and independent of the preceding episode's dynamics.
                env.unwrapped.set_state(qpos, np.zeros(4))
                obs = np.asarray(env.unwrapped._get_obs(), dtype=np.float64)
                ep_rows: list[tuple[np.ndarray, np.ndarray, np.ndarray]] = []
                for _ in range(int(max_steps)):
                    if action_mode == "random":
                        act = rng.uniform(-1.0, 1.0, size=ACTION_DIM)
                    elif action_mode == "biased":
                        act = rng.uniform(0.0, 1.0, size=ACTION_DIM)
                    elif action_mode == "zero":
                        act = np.zeros(ACTION_DIM, dtype=np.float64)
                    else:
                        raise ValueError(f"unknown action_mode {action_mode}")
                    act = np.clip(act * float(action_scale), -1.0, 1.0)
                    nobs, _reward, term, trunc, _info = env.step(act.astype(np.float32))
                    nobs = np.asarray(nobs, dtype=np.float64)
                    states.append(obs)
                    actions.append(act)
                    next_states.append(nobs)
                    ep_rows.append((obs.copy(), act.copy(), nobs.copy()))
                    obs = nobs
                    if term or trunc:
                        break
                episodes.append(ep_rows)
        finally:
            env.close()
    cfg = {"seed": int(seed), "n_episodes": int(n_episodes),
           "max_steps": int(max_steps), "target_mode": target_mode,
           "action_mode": action_mode, "action_scale": float(action_scale),
           "simulator": "gymnasium/Reacher-v5"}
    return TrajectoryBatch(
        states=np.asarray(states, dtype=np.float64).reshape(-1, OBS_DIM),
        actions=np.asarray(actions, dtype=np.float64).reshape(-1, ACTION_DIM),
        next_states=np.asarray(next_states, dtype=np.float64).reshape(-1, OBS_DIM),
        episodes=episodes, config=cfg)


class ActionConditionedMLP:
    """Small real PyTorch MLP: (s_t, a_t) -> s_{t+1}."""

    def __init__(self, hidden: list[int]):
        self.hidden = [int(h) for h in hidden]
        self._net = None
        self._torch = None

    def _build(self):
        import torch
        import torch.nn as nn
        self._torch = torch
        layers: list[Any] = []
        dim = INPUT_DIM
        for h in self.hidden:
            layers += [nn.Linear(dim, h), nn.ReLU()]
            dim = h
        layers += [nn.Linear(dim, OBS_DIM)]
        self._net = nn.Sequential(*layers)

    def fit(self, batch: TrajectoryBatch, *, lr: float, epochs: int,
            seed: int, batch_size: int = 64) -> dict[str, Any]:
        torch = self._torch or __import__("torch")
        self._build()
        torch.manual_seed(seed)
        net = self._net
        x = torch.tensor(np.concatenate([batch.states, batch.actions], axis=1),
                         dtype=torch.float32)
        y = torch.tensor(batch.next_states, dtype=torch.float32)
        opt = torch.optim.Adam(net.parameters(), lr=float(lr))
        loss_fn = torch.nn.MSELoss()
        losses: list[float] = []
        n = x.shape[0]
        bs = max(1, min(int(batch_size), n))
        for _ in range(int(epochs)):
            perm = torch.randperm(n)
            total = 0.0
            for i in range(0, n, bs):
                idx = perm[i:i + bs]
                opt.zero_grad()
                loss = loss_fn(net(x[idx]), y[idx])
                loss.backward()
                opt.step()
                total += float(loss.item()) * len(idx)
            losses.append(total / n)
        return {"final_loss": losses[-1] if losses else None,
                "n_epochs": int(epochs), "n_samples": n}

    def _predict(self, states: np.ndarray, actions: np.ndarray) -> np.ndarray:
        torch = self._torch or __import__("torch")
        self._net.eval()
        with torch.no_grad():
            x = torch.tensor(
                np.concatenate([states, actions], axis=1), dtype=torch.float32)
            return self._net(x).numpy().astype(np.float64)

    def evaluate(self, batch: TrajectoryBatch) -> dict[str, float]:
        """One/multi-step prediction error on held-out episodes (autoregressive)."""
        one = self._predict(batch.states, batch.actions)
        one_err = float(np.mean((one - batch.next_states) ** 2))

        horizon_errors: dict[int, float] = {}
        for k in (5, 10):
            errs: list[float] = []
            for ep in batch.episodes:
                if len(ep) <= k:
                    continue
                s0, a0, s1 = ep[0]
                pred = s0.astype(np.float64)
                truth = ep[k - 1][2].astype(np.float64)
                # step 1
                for t in range(k):
                    a_t = ep[t][1]
                    pred = self._predict(pred[None, :], a_t[None, :])[0]
                errs.append(float(np.mean((pred - truth) ** 2)))
            horizon_errors[k] = float(np.mean(errs)) if errs else float("nan")

        rollout = float(np.mean([v for v in horizon_errors.values()
                                 if math.isfinite(v)])) if horizon_errors else float("nan")
        finite_h = [k for k in (5, 10) if math.isfinite(horizon_errors.get(k, float("nan")))]
        if len(finite_h) >= 2:
            x = np.array(finite_h, dtype=float)
            y = np.array([horizon_errors[k] for k in finite_h], dtype=float)
            slope = float(np.polyfit(x, y, 1)[0])
        else:
            slope = 0.0
        out = {"one_step_mse": one_err, "rollout_mse": rollout,
               "error_growth": slope}
        for k, v in horizon_errors.items():
            out[f"step_{k}_mse"] = v
        return out


@dataclass
class ReacherRun:
    arm: str
    regime_id: str
    seed: int
    applied_config: dict[str, Any]
    config_sha256: str
    data_sha256: str
    test_sha256: str
    model_sha256: str
    metrics: dict[str, float]
    budget: dict[str, Any]
    ok: bool = False
    error: str = ""

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def run_arm(*, arm: str, regime_id: str, seed: int,
            train_cfg: dict[str, Any], test_cfg: dict[str, Any],
            model_cfg: dict[str, Any], out_dir: str | Path,
            epochs: int = 160) -> ReacherRun:
    """Execute one real dynamics-model run and persist its artifacts."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    applied = {"train_data": dict(train_cfg), "test_data": dict(test_cfg),
               "model": dict(model_cfg), "epochs": int(epochs), "seed": int(seed)}
    cfg_sha = sha256_json(applied)
    run = ReacherRun(arm=arm, regime_id=regime_id, seed=seed,
                     applied_config=applied, config_sha256=cfg_sha,
                     data_sha256="", test_sha256="", model_sha256="",
                     metrics={}, budget={"max_epochs": epochs, "seed": seed})
    t0 = time.time()
    try:
        train = generate_trajectories(seed=seed, **train_cfg)
        test = generate_trajectories(seed=seed + 9000, **test_cfg)
        run.data_sha256 = train.digest()
        run.test_sha256 = test.digest()
        model = ActionConditionedMLP(hidden=model_cfg["hidden"])
        fit_info = model.fit(train, lr=float(model_cfg["lr"]), epochs=epochs,
                             seed=seed)
        run.metrics = model.evaluate(test)
        run.metrics["train_final_loss"] = fit_info["final_loss"]
        # Persist a compact, deterministic model signature artifact.
        sig = {"hidden": model.hidden, "lr": model_cfg["lr"],
               "weights_sha": sha256_json(
                   [np.round(w.detach().numpy(), 6).tolist()
                    for w in model._net.parameters()])}
        model_path = out / "model_signature.json"
        model_path.write_text(json.dumps(sig, sort_keys=True), encoding="utf-8")
        run.model_sha256 = sha256_file(model_path)
        run.budget["wall_seconds"] = round(time.time() - t0, 3)
        run.ok = True
    except Exception as exc:  # infrastructure failure recorded, not hidden
        run.ok = False
        run.error = f"{type(exc).__name__}: {exc}"
    (out / "run.json").write_text(json.dumps(
        run.to_dict(), indent=2, sort_keys=True, ensure_ascii=False, default=str),
        encoding="utf-8")
    return run


