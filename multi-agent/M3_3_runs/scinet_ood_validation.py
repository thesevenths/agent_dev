"""M3.3 -- REAL ID + OOD (regime-shift) re-validation of the M2.7 improvement.

Extends the M3.0 REAL 10+10 protocol with an INDEPENDENT out-of-distribution
(OOD) axis. The OOD dataset is a genuine regime shift generated by varying the
physics knob ``t_max`` (8.0 -> 14.0) on the SAME pendulum generator, producing a
new content-addressed ``dataset_version`` (pendulum-a884d327551d) that is NOT
IID with the in-distribution set. A candidate is PRODUCTION-ACCEPTED only when it
improves BOTH the ID and the OOD axis under the identical M3.0 statistical gate
(namespaced ``ood_``); an ID-only gain that collapses under shift is exposed as
ID-overfit and rejected.

Runs the REAL SciNet++ engine (SciNetAdapter -> research_api.cli subprocess,
torch) through the REAL unified dual-layer controller. Only the RESEARCH_HARNESS
evolution entry point is stubbed (orthogonal to the domain gate), exactly as in
M3.0. No FakeRunner anywhere: the domain runner is the production
``cli._build_real_domain_runner`` wired with the OOD config, and the OOD metric
comes from a REAL engine evaluation that reuses the ID-trained checkpoint on the
regime-shift data.

Output: M3_3_runs/scinet_ood_result.json (ID + OOD records + combined verdicts).
"""
from __future__ import annotations

import hashlib
import json
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from research_runtime.cli import _build_real_domain_runner  # noqa: E402
from research_runtime.evolution.evolution_controller import (  # noqa: E402
    run_dual_layer, DEFAULT_ALPHA, HOLDOUT_DIRECTION_MIN_FRACTION,
)
from research_runtime.settings import DEFAULT_SCINET_DIR  # noqa: E402

PROJ = (REPO / "M2_7_runs" / "scinet").resolve()
CFG = (PROJ / "configs" / "pendulum_smoke.yaml").resolve()
ID_DATASET_VERSION = "pendulum-a0e03386be89"
OOD_CFG = (DEFAULT_SCINET_DIR / "configs" / "pendulum_smoke_ood.yaml").resolve()
OOD_DATASET_VERSION = "pendulum-a884d327551d"
OOD_DATASET_DIR = (DEFAULT_SCINET_DIR / "datasets" / "pendulum_smoke_ood_v1").resolve()
SEEDS = tuple(range(50, 60))        # 10 PAIRED seeds
HOLDOUT = tuple(range(60, 70))      # 10 INDEPENDENT holdout seeds
RUN_ROOT = REPO / "M3_3_runs" / "scinet_ood_10seed"
OUT = REPO / "M3_3_runs" / "scinet_ood_result.json"


def _harness_stub(**kw):
    """Harness layer only -- domain layer below is 100% REAL engine."""
    return {
        "schema_version": "stub-harness-layer",
        "dominant_failure": "DECISION_UNCERTAINTY",
        "records": [], "accepted": [], "n_accepted": 0,
    }


def _verify_ood_data() -> dict:
    """Fail-closed verification of the OOD regime-shift dataset on disk.

    Proves the OOD set is a REAL regime shift and not an IID re-read:
      * dataset_version == pendulum-a884d327551d (content-addressed, distinct
        from the ID pendulum-a0e03386be89);
      * data_spec.t_max == 14.0 while the ID set is 8.0 (a genuine physics knob
        change, not a same-generator split_seed shuffle -- which ARCHITECTURE
        AUDIT.md would flag as fake OOD);
      * every split SHA-256 matches the manifest (no tampered / stale file).
    """
    manifest_path = OOD_DATASET_DIR / "manifest.json"
    if not manifest_path.is_file():
        raise FileNotFoundError(f"OOD frozen dataset missing: {manifest_path}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    bad = []
    for split, info in (manifest.get("splits") or {}).items():
        p = OOD_DATASET_DIR / info["file"]
        if hashlib.sha256(p.read_bytes()).hexdigest() != info["sha256"]:
            bad.append(split)
    spec = manifest.get("data_spec") or {}
    return {
        "dataset_version": manifest.get("dataset_version"),
        "declared_ood_t_max": spec.get("t_max"),
        "splits": sorted((manifest.get("splits") or {}).keys()),
        "sha_mismatch": bad,
    }


def _verify_id_data() -> dict:
    """Verify the ID frozen dataset (mirror under M2_7_runs) for SHA integrity."""
    root = PROJ / "datasets" / "pendulum_smoke_v1"
    manifest = json.loads((root / "manifest.json").read_text(encoding="utf-8"))
    bad = []
    for split, info in (manifest.get("splits") or {}).items():
        p = root / info["file"]
        if hashlib.sha256(p.read_bytes()).hexdigest() != info["sha256"]:
            bad.append(split)
    return {
        "dataset_version": manifest.get("dataset_version"),
        "splits": sorted((manifest.get("splits") or {}).keys()),
        "sha_mismatch": bad,
    }


def main() -> dict:
    RUN_ROOT.mkdir(parents=True, exist_ok=True)
    ood = _verify_ood_data()
    idv = _verify_id_data()
    assert ood["dataset_version"] == OOD_DATASET_VERSION, ood
    assert idv["dataset_version"] == ID_DATASET_VERSION, idv
    assert ood["declared_ood_t_max"] == 14.0, ood
    assert not ood["sha_mismatch"], "OOD frozen dataset SHA mismatch -> fail closed"
    assert not idv["sha_mismatch"], "ID frozen dataset SHA mismatch -> fail closed"
    assert OOD_CFG.is_file(), OOD_CFG

    # Real engine runner wired with the OOD config: every evaluate pass writes
    # BOTH backtest_metrics.json (ID) and ood_metrics.json (OOD).
    runner = _build_real_domain_runner("scinet", PROJ, ood_config_path=OOD_CFG)
    t0 = time.time()
    print(f"START real SciNet++ ID+OOD 10+10 validation | "
          f"{time.strftime('%H:%M:%S')}", flush=True)
    print(f"  project_dir={PROJ}", flush=True)
    print(f"  id_dataset_version={ID_DATASET_VERSION}", flush=True)
    print(f"  ood_dataset_version={OOD_DATASET_VERSION} (t_max="
          f"{ood['declared_ood_t_max']})", flush=True)
    print(f"  paired_seeds={SEEDS} holdout_seeds={HOLDOUT}", flush=True)
    print(f"  ood={ood}", flush=True)

    payload = run_dual_layer(
        base_harness=None, tasks=[], heldout_task=None,
        run_root=RUN_ROOT, repo_root=REPO, rounds=1, max_minutes=1.0,
        domain="scinet", domain_base_config=str(CFG),
        project_dir=str(PROJ), dataset_version=ID_DATASET_VERSION,
        domain_seeds=SEEDS, domain_holdout_seeds=HOLDOUT,
        domain_require_frozen_manifest=True,
        domain_runner=runner, harness_evolve=_harness_stub,
        ood_config_path=str(OOD_CFG))
    elapsed = time.time() - t0

    dom = payload["domain_layer"]
    rows = []
    for r in dom["records"]:
        rows.append({
            "target": r.get("target"), "new_value": r.get("new"),
            "n_valid": r.get("n_valid"), "n_invalid": r.get("n_invalid"),
            "mean_improvement": r.get("mean_improvement"),
            "std_improvement": r.get("std_improvement"),
            "baseline_mean": r.get("baseline_mean"),
            "holdout_improvement": r.get("holdout_improvement"),
            "holdout_n_valid": r.get("holdout_n_valid"),
            "holdout_n_seeds": r.get("holdout_n_seeds"),
            "holdout_n_invalid": r.get("holdout_n_invalid"),
            "holdout_direction_fraction": r.get("holdout_direction_fraction"),
            "statistics": r.get("statistics"),
            "decision": r.get("decision"),
            # OOD axis
            "ood_mean_improvement": r.get("ood_mean_improvement"),
            "ood_std_improvement": r.get("ood_std_improvement"),
            "ood_baseline_mean": r.get("ood_baseline_mean"),
            "ood_holdout_improvement": r.get("ood_holdout_improvement"),
            "ood_holdout_n_valid": r.get("ood_holdout_n_valid"),
            "ood_holdout_direction_fraction": r.get("ood_holdout_direction_fraction"),
            "ood_statistics": r.get("ood_statistics"),
            "ood_decision": r.get("ood_decision"),
        })
    out = {
        "protocol": "M3.0-student-t-holm",
        "axis": "ID + OOD(regime-shift)",
        "domain": "scinet",
        "engine": "REAL SciNet++ (SciNetAdapter / research_api.cli / torch)",
        "domain_runner_is_real_engine": True,
        "harness_layer_stubbed": True,
        "harness_stub_rationale": (
            "M3.3 validates the DOMAIN statistical gate on an ID+OOD pair; the "
            "harness layer is orthogonal. No FakeRunner is used for the domain "
            "layer."),
        "id_dataset_version": ID_DATASET_VERSION,
        "ood_dataset_version": OOD_DATASET_VERSION,
        "ood_t_max": ood["declared_ood_t_max"],
        "ood_is_regime_shift_not_iid": True,
        "frozen_id_dataset": idv,
        "frozen_ood_dataset": ood,
        "paired_seeds": list(SEEDS), "holdout_seeds": list(HOLDOUT),
        "elapsed_seconds": round(elapsed, 2),
        "statistics_protocol": dom.get("statistics_protocol"),
        "n_accepted": dom["n_accepted"], "n_rejected": dom["n_rejected"],
        "n_inconclusive": dom["n_inconclusive"],
        "ood_n_accepted": dom.get("ood_n_accepted"),
        "ood_n_rejected": dom.get("ood_n_rejected"),
        "ood_n_inconclusive": dom.get("ood_n_inconclusive"),
        "records": rows,
    }
    OUT.write_text(json.dumps(out, indent=2, ensure_ascii=False, sort_keys=True),
                   encoding="utf-8")
    print(f"\nDONE elapsed={elapsed:.1f}s "
          f"accept={dom['n_accepted']} reject={dom['n_rejected']} "
          f"inconclusive={dom['n_inconclusive']}", flush=True)
    print(f"  OOD axis: accept={dom.get('ood_n_accepted')} "
          f"reject={dom.get('ood_n_rejected')} "
          f"inconclusive={dom.get('ood_n_inconclusive')}", flush=True)
    for r in rows:
        st = r.get("statistics") or {}
        ood_st = r.get("ood_statistics") or {}
        print(f"  lr={r['new_value']!s:<7} ID mean={r['mean_improvement']} "
              f"ID->{r['decision']:<12} | OOD mean={r['ood_mean_improvement']} "
              f"OOD->{r['ood_decision']}", flush=True)
    return out


if __name__ == "__main__":
    main()
